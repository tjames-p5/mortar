#!/usr/bin/env node
/* Writes Mortar's default native tokens (neutral light and dark palettes,
   densities and scales) from src/native-theme.ts into the Swift package and
   the Compose library. Run `npm run native:tokens` after changing tokens.css
   and native-theme.ts; tests/native.test.mjs fails while the files differ. */

import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

export const SWIFT_FILE = "native/apple/Sources/Mortar/MortarTokens.swift";
export const KOTLIN_FILE =
  "native/android/mortar/src/main/kotlin/codes/tony/mortar/MortarTokens.kt";

const camel = (...parts) =>
  parts
    .map((p, i) => (i ? String(p)[0].toUpperCase() + String(p).slice(1) : p))
    .join("");

/* Every scale as [name, value, kind], named after its tokens.css property. */
function scales(s) {
  return [
    ...Object.entries(s.space).map(([k, v]) => [`space${k}`, v, "size"]),
    ...Object.entries(s.radius).map(([k, v]) => [
      k === "md" ? "radius" : camel("radius", k),
      v,
      "size",
    ]),
    ...Object.entries(s.weight).map(([k, v]) => [camel("weight", k), v, "int"]),
    ...Object.entries(s.tracking).map(([k, v]) => [
      camel("tracking", k),
      v,
      "size",
    ]),
    ...Object.entries(s.leading).map(([k, v]) => [
      camel("leading", k),
      v,
      "size",
    ]),
    ["icon", s.icon, "size"],
    ["focusOffset", s.focusOffset, "size"],
    ["touchTarget", s.touchTarget, "size"],
    ["scrimOpacity", s.scrimOpacity, "size"],
  ];
}

const HEADER = (comment) =>
  `${comment} Generated by scripts/native-tokens.mjs from src/native-theme.ts.
${comment} Do not edit: change tokens.css and native-theme.ts, then run
${comment} \`npm run native:tokens\`.
`;

const digits = (colour) => colour.slice(1).toUpperCase();

export function swift(theme, s) {
  const keys = Object.keys(theme.light);
  const densityKeys = Object.keys(s.density.comfortable);
  const palette = (p) =>
    `MortarPalette(\n${keys.map((k) => `        ${k}: 0x${digits(p[k])}`).join(",\n")}\n    )`;
  const density = (d) =>
    `MortarDensity(${densityKeys.map((k) => `${k}: ${d[k]}`).join(", ")})`;
  const struct = (name, doc, fields, type) => `/// ${doc}
public struct ${name}: Sendable, Equatable {
${fields.map((k) => `    public var ${k}: ${type}`).join("\n")}

    public init(
${fields.map((k) => `        ${k}: ${type}`).join(",\n")}
    ) {
${fields.map((k) => `        self.${k} = ${k}`).join("\n")}
    }
}
`;
  return `${HEADER("//")}
${struct("MortarPalette", "One appearance's colours, as 0xRRGGBB.", keys, "UInt32")}
${struct("MortarDensity", "Control height, padding, font size and row padding, in points.", densityKeys, "Double")}
/// Mortar's neutral palettes, densities and scales. Sizes are in points.
public enum MortarTokens {
    public static let light = ${palette(theme.light)}
    public static let dark = ${palette(theme.dark)}

${Object.entries(s.density)
  .map(([k, d]) => `    public static let ${k} = ${density(d)}`)
  .join("\n")}

${scales(s)
  .map(
    ([name, v, kind]) =>
      `    public static let ${name}: ${kind === "int" ? "Int" : "Double"} = ${v}`,
  )
  .join("\n")}
}
`;
}

export function kotlin(theme, s) {
  const keys = Object.keys(theme.light);
  const densityKeys = Object.keys(s.density.comfortable);
  const palette = (p) =>
    `MortarPalette(\n${keys.map((k) => `        ${k} = 0xFF${digits(p[k])},`).join("\n")}\n    )`;
  const float = (v) => `${v}f`;
  const density = (d) =>
    `MortarDensity(${densityKeys.map((k) => `${k} = ${float(d[k])}`).join(", ")})`;
  return `${HEADER("//")}
package codes.tony.mortar

/** One appearance's colours, as 0xFFRRGGBB, the form Compose's Color(Long) takes. */
public data class MortarPalette(
${keys.map((k) => `    public val ${k}: Long,`).join("\n")}
)

/** Control height, padding, font size and row padding, in dp. */
public data class MortarDensity(
${densityKeys.map((k) => `    public val ${k}: Float,`).join("\n")}
)

/** Mortar's neutral palettes, densities and scales. Sizes are in dp. */
public object MortarTokens {
    public val light: MortarPalette = ${palette(theme.light)}
    public val dark: MortarPalette = ${palette(theme.dark)}

${Object.entries(s.density)
  .map(([k, d]) => `    public val ${k}: MortarDensity = ${density(d)}`)
  .join("\n")}

${scales(s)
  .map(
    ([name, v, kind]) =>
      `    public const val ${name}${kind === "int" ? `: Int = ${v}` : `: Float = ${float(v)}`}`,
  )
  .join("\n")}
}
`;
}

/** The token files as they should be, keyed by path from the repo root. */
export async function nativeTokenFiles() {
  const { nativeTheme, NATIVE_SCALES } = await import(
    pathToFileURL(join(ROOT, "dist/native-theme.js")).href
  );
  const theme = nativeTheme();
  return {
    [SWIFT_FILE]: swift(theme, NATIVE_SCALES),
    [KOTLIN_FILE]: kotlin(theme, NATIVE_SCALES),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [path, text] of Object.entries(await nativeTokenFiles())) {
    await mkdir(dirname(join(ROOT, path)), { recursive: true });
    await writeFile(join(ROOT, path), text);
    console.log(`wrote ${path}`);
  }
}
